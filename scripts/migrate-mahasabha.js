#!/usr/bin/env node
// ============================================================================
// migrate-mahasabha.js
//
// पुरानी "MahasabhaMembers" Google Sheet का CSV export लेकर नए Postgres
// `panchayat_memberships` table के लिए SQL INSERT statements बनाता है।
//
// ⚠️ इसे चलाने से पहले migration 0010_extend_panchayat_memberships.sql ज़रूर
// लगी होनी चाहिए — वरना नीचे इस्तेमाल हो रहे payment_received/form_data जैसे
// columns मौजूद नहीं होंगे और हर INSERT fail होगा।
//
// इस्तेमाल:
//   node migrate-mahasabha.js <mahasabha-export.csv> <members-export.csv> \
//     > 0012_migrated_mahasabha.sql
//
// ── member_gahoi_id resolution ───────────────────────────────────────────────
// पुरानी sheet में GahoiId कॉलम सीधे मौजूद है (matrimony वाली sheet से अलग —
// वहाँ सिर्फ़ email था) — ज़्यादातर rows में इस्तेमाल हो सकता है। लेकिन कुछ बहुत
// पुरानी entries में GahoiId खाली हो सकता है (feature बाद में जुड़ा था), इसलिए
// email/mobile से भी एक fallback lookup रखा गया है (वही members-CSV lookup जो
// migrate-matrimony.js भी इस्तेमाल करती है)।
//
// यह सिर्फ़ MahasabhaMembers sheet migrate करती है — अलग "MahasabhaPayments"
// sheet (Razorpay order/payment IDs) या Members.MahasabhaData JSON column
// scope में नहीं है (ये फ़िलहाल के Mahasabha manual-payment workflow के लिए
// ज़रूरी नहीं, चूँकि TransactionRef/TransactionMode यहीं form_data में सुरक्षित
// रहते हैं)।
//
// ⚠️ असल MahasabhaMembers.csv (Gahoi_Portal.xlsx) चलाने पर पता चला — इस sheet का
// असली header-structure Code.gs के MSM_HEADERS constant से काफ़ी अलग निकला
// (Shulk/PaymentMode/TransactionRef/PaymentReceived* जैसे कॉलम सिरे से मौजूद ही
// नहीं; बदले में MoolNiwas/Address/PhotoUrl/ForwardedBy/ForwardedAt/Hidden और
// कई खाली Reserved16,21-30 कॉलम हैं)। यानी live sheet किसी और/बाद के code-version
// से बनी, जो हमारे पास मौजूद Code.gs से मेल नहीं खाता — बिल्कुल Street/
// StreetAddress जैसी situation। इसलिए यह script **दोनों shape defensively सपोर्ट
// करती है** (जो मिले वो लो, ना मिले तो चुपचाप छोड़ो) — किसी एक version को सही
// मानकर hardcode नहीं किया गया। FullFormData में एक "signature" base64-image
// field भी मिला (हाथ से किए गए हस्ताक्षर की तस्वीर) — जान-बूझकर हटाया नहीं गया
// (असली applicant-data है), पर बड़े rows-count पर form_data jsonb का आकार बढ़ा
// सकता है, आगे ध्यान रखें।
// ============================================================================

const { readCsvFile, sqlStr, sqlBool, sqlJsonb, sqlNum, buildMembersLookup } = require("./_lib/csv-utils");

function main() {
  const msmCsvPath = process.argv[2];
  const membersCsvPath = process.argv[3];
  if (!msmCsvPath || !membersCsvPath) {
    console.error("Usage: node migrate-mahasabha.js <mahasabha-export.csv> <members-export.csv>");
    process.exit(1);
  }

  const { dataRows, get } = readCsvFile(msmCsvPath);
  const lookup = buildMembersLookup(membersCsvPath);

  console.log("-- ============================================================================");
  console.log(`-- Auto-generated by migrate-mahasabha.js — ${dataRows.length} rows from ${msmCsvPath}`);
  console.log("-- चलाने से पहले migration 0010_extend_panchayat_memberships.sql लगी है, यह ज़रूर");
  console.log("-- सुनिश्चित करें, वरना हर INSERT यहाँ fail होगा (नए columns चाहिए)।");
  console.log("-- ============================================================================\n");

  let inserted = 0, skippedEmpty = 0, skippedNoOwner = 0;

  dataRows.forEach((row) => {
    const email = get(row, "Email");
    if (!email || !email.trim()) { skippedEmpty++; return; }

    const legacyGahoiId = get(row, "GahoiId");
    const mobile = get(row, "Mobile");
    const memberGahoiId = (legacyGahoiId && legacyGahoiId.trim())
      ? legacyGahoiId.trim()
      : lookup.byGahoiId(email, mobile);

    if (!memberGahoiId) {
      skippedNoOwner++;
      console.error(`⏭  Skipped Mahasabha application for "${email}" — members-CSV में कोई matching gahoi_id नहीं मिला।`);
      return;
    }

    let fullFormData = {};
    try { fullFormData = JSON.parse(get(row, "FullFormData") || "{}"); } catch { /* कभी-कभी खाली/malformed */ }

    // दोनों header-shapes को defensively पढ़ना — जो कॉलम मौजूद नहीं, get() वैसे भी
    // खाली string लौटाता है (कोई error नहीं), इसलिए missing fields अपने-आप
    // form_data में खाली/छूट जाते हैं
    const forwardedBy = get(row, "PaymentForwardedBy") || get(row, "ForwardedBy");
    const forwardedAt = get(row, "PaymentForwardedAt") || get(row, "ForwardedAt");
    const status = get(row, "AppStatus") || get(row, "Status") || "Pending";

    const formData = {
      panchayat: get(row, "Panchayat") || "",
      kshetra: get(row, "KshetriyaPanchayat") || "",
      fatherOrHusband: get(row, "FatherOrHusband") || "",
      vyavsay: get(row, "Vyavsay") || "",
      shiksha: get(row, "Shiksha") || "",
      dob: get(row, "DOB") || "",
      moolNiwas: get(row, "MoolNiwas") || "",
      address: get(row, "Address") || "",
      photoUrl: get(row, "PhotoUrl") || "",
      paymentMode: get(row, "PaymentMode") || "",
      transactionRef: get(row, "TransactionRef") || "",
      transactionDate: get(row, "TransactionDate") || "",
      paymentNote: get(row, "PaymentNote") || "",
      rejectedReason: get(row, "RejectedReason") || "",
      remarks: get(row, "Remarks") || "",
      fullFormData,
    };

    const cols = [
      "member_gahoi_id", "level", "status", "fee", "applied_at", "approved_by", "approved_at",
      "form_data", "payment_received", "payment_received_by", "payment_received_at",
      "payment_forwarded", "payment_forwarded_by", "payment_forwarded_at",
      "form_submitted", "form_submitted_by", "form_submitted_at",
    ];

    const timestamp = get(row, "Timestamp");
    const approvedAt = get(row, "ApprovedAt");
    const paymentReceivedAt = get(row, "PaymentReceivedAt");
    const formSubmittedAt = get(row, "FormSubmittedAt");

    const vals = [
      sqlStr(memberGahoiId), "'Mahasabha'", sqlStr(status),
      sqlNum(get(row, "Shulk")), timestamp ? sqlStr(timestamp) : "now()", sqlStr(get(row, "ApprovedBy")),
      approvedAt ? sqlStr(approvedAt) : "NULL",
      sqlJsonb(formData), sqlBool(get(row, "PaymentReceived")), sqlStr(get(row, "PaymentReceivedBy")),
      paymentReceivedAt ? sqlStr(paymentReceivedAt) : "NULL",
      // payment_forwarded — असली sheet में कोई boolean column नहीं, ForwardedAt
      // भरा होने को ही "forwarded हो चुका" मान रहे हैं
      sqlBool(get(row, "PaymentForwarded") || (forwardedAt ? "true" : "")),
      sqlStr(forwardedBy), forwardedAt ? sqlStr(forwardedAt) : "NULL",
      sqlBool(get(row, "FormSubmitted")), sqlStr(get(row, "FormSubmittedBy")),
      formSubmittedAt ? sqlStr(formSubmittedAt) : "NULL",
    ];

    console.log(`insert into panchayat_memberships (${cols.join(", ")}) values (${vals.join(", ")});`);
    inserted++;
  });

  console.error(`\n✅ ${inserted} Mahasabha applications converted।`);
  console.error(`   ${skippedEmpty} खाली rows छोड़े गए, ${skippedNoOwner} rows gahoi_id ना मिलने से छोड़े गए।`);
}

main();
